#!/usr/bin/env python3
"""Generate cohesive Q-version (Chibi / Puffy) pixel icons for Phosprite.

Conforms to Phosprite Q Icon Manifest v1.0:
- Standard: 20x20 RGBA PNG (16x16 safe box, 2px transparent padding)
- Compact:  16x16 RGBA PNG (12x12 safe box, 2px transparent padding)
- Outline:  #282C40 (4-connected outline so outer corners are rounded, no sharp spikes)
- Highlight: #FFFFFF (2x1px on 20x20, 1x1px on 16x16)
- Palette:  6 soft pastel 2-tone pairs (light + shadow)
"""

from pathlib import Path
from PIL import Image

OUTLINE = (0x28, 0x2C, 0x40, 255)
WHITE = (0xFF, 0xFF, 0xFF, 255)
TRANSPARENT = (0, 0, 0, 0)

PAL = {
    ".": TRANSPARENT,
    " ": TRANSPARENT,
    "o": OUTLINE,
    "W": WHITE,
    # Cream White
    "C": (0xFF, 0xFD, 0xF9, 255),
    "c": (0xE4, 0xDF, 0xD3, 255),
    # Butter Yellow
    "Y": (0xFF, 0xE2, 0x8A, 255),
    "y": (0xF4, 0xBE, 0x4E, 255),
    # Soft Sky
    "B": (0x8C, 0xCB, 0xFF, 255),
    "b": (0x5A, 0xA6, 0xF0, 255),
    # Peach Coral
    "P": (0xFF, 0xA3, 0x94, 255),
    "p": (0xF0, 0x75, 0x63, 255),
    # Mint Jelly
    "M": (0x86, 0xE3, 0xBE, 255),
    "m": (0x4F, 0xC4, 0x97, 255),
    # Lilac Mist
    "L": (0xD0, 0xD6, 0xE8, 255),
    "l": (0xA5, 0xB0, 0xCC, 255),
}


def auto_outline(grid: list[str]) -> list[list[tuple[int, int, int, int]]]:
    """Convert an ASCII art grid (16x16 or 12x12) into an RGBA matrix with 4-connected #282C40 outline."""
    h = len(grid)
    w = len(grid[0])
    # Pad by 2px on all sides -> 20x20 or 16x16
    out_w, out_h = w + 4, h + 4
    px = [[TRANSPARENT for _ in range(out_w)] for _ in range(out_h)]

    # First place fill pixels
    for y in range(h):
        row = grid[y]
        for x in range(w):
            ch = row[x]
            if ch not in (".", " "):
                px[y + 2][x + 2] = PAL[ch]

    # Add 4-connected outline around any non-transparent, non-outline pixel
    # unless 'o' was already placed explicitly
    outlined = [row[:] for row in px]
    for y in range(1, out_h - 1):
        for x in range(1, out_w - 1):
            if px[y][x] == TRANSPARENT:
                has_neighbor = any(
                    px[y + dy][x + dx] not in (TRANSPARENT, OUTLINE)
                    for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1))
                )
                if has_neighbor:
                    outlined[y][x] = OUTLINE
    return outlined


def save_icon(rel_path: str, grid: list[str], root: Path) -> Path:
    expected = len(grid)
    for i, r in enumerate(grid):
        assert len(r) == expected, f"{rel_path} row {i} length {len(r)} != {expected}"
    matrix = auto_outline(grid)
    h = len(matrix)
    w = len(matrix[0])
    img = Image.new("RGBA", (w, h), TRANSPARENT)
    for y in range(h):
        for x in range(w):
            img.putpixel((x, y), matrix[y][x])
    target = root / rel_path
    target.parent.mkdir(parents=True, exist_ok=True)
    img.save(target, "PNG")
    return target


