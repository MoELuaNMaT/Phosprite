def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    q_root = repo_root / "assets" / "graphics" / "q_icons"

    # Normalize polygon_select trailing space if any
    ICONS_20["tools/polygon_select.png"] = [
        r.strip() for r in ICONS_20["tools/polygon_select.png"]
    ]

    generated = []
    for rel, grid in ICONS_20.items():
        generated.append(save_icon(rel, grid, q_root))
    for rel, grid in ICONS_16.items():
        generated.append(save_icon(rel, grid, q_root))

    print(f"Generated {len(generated)} Q-version pixel icons in {q_root}")

    # Generate a 4x upscaled contact sheet for visual QA
    cols = 10
    cell = 96
    rows = (len(generated) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * cell, rows * cell), (0xFA, 0xF8, 0xF3, 255))
    for idx, path in enumerate(sorted(generated)):
        im = Image.open(path).convert("RGBA")
        scale = 4
        up = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
        r, c = divmod(idx, cols)
        ox = c * cell + (cell - up.width) // 2
        oy = r * cell + (cell - up.height) // 2
        sheet.paste(up, (ox, oy), up)
    preview_path = repo_root.parent / "q_icons_preview.png"
    sheet.save(preview_path, "PNG")
    print(f"Saved preview contact sheet: {preview_path}")


if __name__ == "__main__":
    main()
